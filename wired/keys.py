# Modifier bit values stored in the profile (inferred from the shortcut dialog).
MOD_CTRL = 0x01
MOD_SHIFT = 0x02
MOD_ALT = 0x04
MOD_WIN = 0x08
MOD_NAMES = ((MOD_CTRL, "Ctrl"), (MOD_SHIFT, "Shift"), (MOD_ALT, "Alt"), (MOD_WIN, "Win"))


def key_name(vk: int) -> str:
    if vk in VK_NAMES:
        return VK_NAMES[vk]
    if 0xF0 <= vk <= 0xF8:
        return MOUSE_NAMES.get(vk, f"Button {vk:02X}")
    if 0x30 <= vk <= 0x5A:
        return chr(vk)
    return f"VK 0x{vk:02X}"


def key_id_for_vk(vk: int) -> int:
    """Apply the original's physical scan-code re-resolution."""
    row_id = None
    scan = None
    for rvk, rid, rscan in KEY_TABLE:
        if rvk == vk:
            row_id = rid
            scan = rscan
            break
    if row_id is None:
        return 0
    if 4 <= row_id <= 0x45:
        target = _map_virtual_key(vk, 0)
        if target:
            for _rvk, rid, rscan in KEY_TABLE:
                if rscan == target:
                    return rid
    return row_id


def vk_for_key_id(key_id: int) -> int:
    for vk, kid, _scan in KEY_TABLE:
        if kid == key_id:
            return vk
    return 0


def key_id_name(key_id: int) -> str:
    vk = vk_for_key_id(key_id)
    if vk:
        return key_name(vk)
    return f"Key 0x{key_id:02X}"


def shortcut_name(key: int, mods: int) -> str:
    """Name a stored shortcut; ``key`` is a firmware key id, not a VK code."""
    if not key and not mods:
        return "Shortcut"
    parts = [name for bit, name in MOD_NAMES if mods & bit]
    parts.append(key_id_name(key) if key else "?")
    return "+".join(parts)


def _map_virtual_key(vk: int, map_type: int) -> int:
    if sys.platform != "win32":
        return 0
    try:
        return int(ctypes.windll.user32.MapVirtualKeyW(vk, map_type)) & 0xFF
    except Exception:
        return 0


def normalize_vk(vk: int) -> int:
    """Collapse left/right modifier VKs to their generic form for display."""
    return {
        0xA2: 0x11, 0xA3: 0x11,
        0xA0: 0x10, 0xA1: 0x10,
        0xA4: 0x12, 0xA5: 0x12,
        0x5B: 0x5B, 0x5C: 0x5B,
    }.get(vk, vk)
