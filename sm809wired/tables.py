assert len(DPI_CODES) == 121


def dpi_index(value: int) -> int:
    """Profile DPI value (stored as DPI/50) -> table index: value itself up to 120,
    value // 2 above that (the app's rule for this sensor)."""
    if value < 1:
        raise ValueError("DPI value must be >= 1")
    idx = value if value < 121 else value // 2
    if idx > 120:
        raise ValueError(f"DPI value {value} is out of range for this sensor")
    return idx


def dpi_code(value: int) -> int:
    """Profile DPI value -> the one-byte stage code sent in the 0x11 block."""
    return DPI_CODES[dpi_index(value)]
