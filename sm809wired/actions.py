ACTION_SHORTCUT = 0x15
ACTION_FIRE = 0x0A
MACRO_ACTIONS = (0x16, 0x39, 0x79)


def slot_entry(action: int, shortcut_b: int = 0, shortcut_c: int = 0,
               fire_count: int = 0, fire_interval: int = 0) -> bytes:
    """4 wire bytes for one button slot whose Data.ini flag is 1 (computed)."""
    if action in MACRO_ACTIONS:
        raise NotImplementedError(f"macro action 0x{action:02X} is not supported yet")
    a, b, c, d = ACTIONS.get(action, (0, 0, 0, 0))
    if action == ACTION_SHORTCUT:
        b, c = shortcut_b & 0xFF, shortcut_c & 0xFF
    elif action == ACTION_FIRE:
        b, c, d = 0xF0, fire_interval & 0xFF, fire_count & 0xFF
    return bytes((a & 0xFF, b & 0xFF, c & 0xFF, d & 0xFF))
